'''
This script read PCA coordinate file generated by PLINK2
 and population information file, and then output 2D scatter
  plot in PDF   
'''

from openpyxl.chart import shapes
from ast import parse
import pandas as pd
import matplotlib.pyplot as plt
# pyrefly: ignore [missing-import]
import matplotlib
matplotlib.use('Agg')
import numpy as np
import argparse
import os
import seaborn as sns

from oval_plot import plot_ovals

MARKERS = [
    "o",  # 0: Circle
    "s",  # 1: Square
    "^",  # 2: Triangle up
    "v",  # 3: Triangle down
    "<",  # 4: Triangle left
    ">",  # 5: Triangle right
    "D",  # 6: Diamond
    "d",  # 7: Thin diamond
    "p",  # 8: Pentagon
    "P",  # 9: Plus in circle
    "*",  # 10: Star
    "X",  # 11: X
    "h",  # 12: Hexagon
    "H",  # 13: Thin hexagon
    "8"  # 14: Octagon
]

CMAP = [
    "#1f77b4",  # 0: Blue
    "#ff7f0e",  # 1: Orange
    "#2ca02c",  # 2: Green
    "#d62728",  # 3: Red
    "#9467bd",  # 4: Purple
    "#8c564b",  # 5: Brown
    "#e377c2",  # 6: Pink
    "#7f7f7f",  # 7: Gray
    "#bcbd22",  # 8: Olive
    "#17becf"  # 9: Cyan
]

def read_eigenval(eigenval_file):
    eigenval_df = pd.read_table(eigenval_file,sep="\t", header=None)
    
    _total = eigenval_df[0].sum()
    eigenval_df['VE'] = eigenval_df[0] / _total
    
    return eigenval_df

def annotate_points(xs, ys, do_annotate, ax, annotate_char='*'):

    for x, y, annotate in zip(xs, ys, do_annotate):
        if annotate:
            ax.annotate(
                annotate_char,
                (x, y),  # Position to place the text
                fontsize=6,  # Adjust font size as needed
                ha='center',  # Horizontal alignment
                va='center'  # Vertical alignment
            )

def load_data(pca_file, pop_file, pop_col=None, pca_x=1, pca_y=2):

    # Read PCA coordinate file
    pca_df = pd.read_table(pca_file,sep="\t")
    # From #IID value take only ID part split by "-" 
    pca_df['ID'] = [_.split('-')[0] for _ in pca_df['#IID']]

    # Read eigenvalue file if it exsits
    eigenval_file = pca_file.replace('.eigenvec', '.eigenval')
    if os.path.exists(eigenval_file):
        eigenval_df = read_eigenval(eigenval_file)
        variance_ratio = [eigenval_df['VE'][pca_x-1], eigenval_df['VE'][pca_y-1]]
    else:
        variance_ratio = None
        
    # Read population information file
    pop_df = pd.read_table(pop_file,sep="\t")
    # Check if pop file has collumn "ID" 
    if "ID" not in pop_df.columns:
        raise ValueError("Pop file must have 'ID' column.")

    # Set default column for shape and color
    if pop_col is None:
        pop_col = pop_df.columns[1]

    # Merge PCA coordinate and population information
    pca_df = pd.merge(pca_df, pop_df, on='ID', how='left')
    pca_df = pca_df.sort_values(by=pop_col)
    pca_df = pca_df.reset_index(drop=True)

    return pca_df, variance_ratio

def add_oval(x, y, pops, ax):

    subdf = pd.DataFrame({
        "x": x,
        "y": y,
        "pops": pops,
    })

    plot_ovals(
        ax=ax,
        result=subdf,
        mean_type=False,
        alpha_fill=0.18
    )

def plot_pca(pca_file,
      pop_file,
      output_file,
      pca_x=1,
      pca_y=2,
      pop_col=None,
      annotate_col=None,
      ellipse_col=None
      ):
    
    # Load data
    pca_df, variance_ratio = load_data(pca_file, pop_file, pop_col, pca_x, pca_y)

    # Make dictionaries to map POP to color and marker shape

    pop_color = {}
    pop_marker = {}
    unique_pop = pca_df[pop_col].unique()

    for i, pop in enumerate(unique_pop):
        pop_marker[pop] = MARKERS[i % len(MARKERS)]
        pop_color[pop] = CMAP[i % len(CMAP)]

    fig, ax = plt.subplots(figsize=(12, 8))

    # Create 2D scatter plot with color and shape
    sns.scatterplot(
        data=pca_df,
        x=f'PC{pca_x}',
        y=f'PC{pca_y}',
        hue=pop_col,
        style=pop_col,
        palette=pop_color,
        markers=pop_marker,
        alpha=0.8,
        edgecolors='k',
        s=15,
        ax=ax
    )

    # Add annotation if specified
    if annotate_col and annotate_col in pca_df.columns:
        # Add text annotations for each point
        annotate_points(pca_df[f'PC{pca_x}'], pca_df[f'PC{pca_y}'],
                 pca_df[annotate_col], ax, '*')

    # Oval plot
    if ellipse_col and ellipse_col in pca_df.columns:
        add_oval(pca_df[f'PC{pca_x}'], pca_df[f'PC{pca_y}'],
                 pca_df[ellipse_col], ax)

    # legend
    plt.legend(
        title='Population',
        bbox_to_anchor=(1.05, 1),
        loc='upper left',
        borderaxespad=0.,
        ncol=1,
        fontsize=6
    )

    # Add % of variance explained on x and y axes   
    if variance_ratio:
        plt.xlabel(f'PC{pca_x} ({variance_ratio[0]:.2%})')
        plt.ylabel(f'PC{pca_y} ({variance_ratio[1]:.2%})')
    else:
        plt.xlabel(f'PC{pca_x}')
        plt.ylabel(f'PC{pca_y}')
        
    plt.title('PCA')

    plt.tight_layout()
    plt.savefig(output_file, dpi=300)
    plt.close() 

    pca_df.to_csv(output_file + '.csv', sep='\t', index=False)

